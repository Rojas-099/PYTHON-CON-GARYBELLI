SELECT * FROM usuarios; --trae y muestra la informacion de la tabla usuarios

SELECT nombre from usuarios; -- trae y muestra la informacion de la columna 'nombre' en la tabla usuarios

SELECT edad, apellido FROM usuarios; -- trae y muestra la informacion de las columnas 'edad y apellido' de la tabla usuarios 

SELECT usuario_id, apellido FROM usuarios; -- trae y muestra la informacion de las columnas 'usuario_id y apellido' de la tabla usuarios

