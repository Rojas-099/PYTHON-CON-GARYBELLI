# Remplazar subcadenas en una cadena
cadena = "Hola Juan"
print(f'cadena original{cadena}')

# Remplazar la cadena "juan" por "mundo"
nueva_cadena = cadena.replace("Juan","mundo")
print(f"Nueva cadena reemplazada: {nueva_cadena}")

# Remplazar la cadena "Hola" por "Adios"
nueva_cadena = cadena.replace("Hola","Adios")
print(f"Nueva cadena reemplazada: {nueva_cadena}")