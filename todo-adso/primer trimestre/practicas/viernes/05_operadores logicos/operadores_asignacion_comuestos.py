#operadores_asignacion_comuestos

#delaracion y asignacion multiples variables 

a, b = 10, 15

#operador compuesto de suma(+=)
a += b
print(f'operador a += b es: {a}')

#esto equivale a : a + b, es decir , a = 10 + 15 = 25 

#operador compuesto de resta(-=)
a -= b
print(f'operador a -= b es: {a}')

#esto equivale a : a - b, es decir , a = 25 - 15 = 10

#operador compuesto de multiplicacion(*=)
a *= b
print(f'operador a *= b es: {a}')

#esto equivale a : a * b, es decir , a = 10 * 15 = 150

#operador compuesto de division(/=)
a /= b
print(f'operador a /= b es: {a}')

#esto equivale a : a / b, es decir , a = 150 / 15 = 10.0